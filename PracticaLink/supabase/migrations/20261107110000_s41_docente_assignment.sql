-- PostgreSQL 18 exige UPDATE sobre al menos una columna para FOR SHARE.
-- Conservar los bloqueos de identidad/membresia/rol: una lectura sin bloqueo o
-- FOR KEY SHARE no protege las desactivaciones concurrentes de atributos.
-- RLS debe estar activo y el definer no debe ser propietario de estas tablas.
DO $$
DECLARE v_tabla TEXT;
BEGIN
    FOREACH v_tabla IN ARRAY ARRAY['usuario','usuario_rol','rol'] LOOP
        IF NOT EXISTS (
            SELECT 1 FROM pg_catalog.pg_class c
            WHERE c.oid = pg_catalog.to_regclass('public.' || v_tabla)
              AND c.relrowsecurity
              AND c.relowner <> (SELECT oid FROM pg_catalog.pg_roles
                                WHERE rolname='pl_s41_docente_owner')
        ) THEN
            RAISE EXCEPTION 'RLS/propietario incompatible para bloqueo S4.1 en %', v_tabla;
        END IF;
    END LOOP;
END $$;
