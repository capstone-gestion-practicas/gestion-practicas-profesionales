CREATE TABLE public.historial_asignacion_docente (
    id_historial BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_practica BIGINT NOT NULL REFERENCES public.practica(id_practica) ON DELETE RESTRICT,
    id_docente_anterior BIGINT REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
    id_docente_nuevo BIGINT REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
    id_actor BIGINT NOT NULL REFERENCES public.usuario(id_usuario) ON DELETE RESTRICT,
    fecha_cambio TIMESTAMPTZ NOT NULL DEFAULT clock_timestamp(),
    motivo TEXT,
    CONSTRAINT historial_asignacion_docente_cambio CHECK (
        id_docente_anterior IS DISTINCT FROM id_docente_nuevo
        AND (id_docente_anterior IS NULL OR motivo IS NOT NULL AND btrim(motivo) <> '')
    )
);
CREATE INDEX historial_asignacion_docente_practica_fecha_idx
    ON public.historial_asignacion_docente(id_practica, fecha_cambio DESC, id_historial DESC);

ALTER TABLE public.practica ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.historial_asignacion_docente ENABLE ROW LEVEL SECURITY;

DO $$ BEGIN
    CREATE ROLE pl_s41_docente_owner NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$ BEGIN
    CREATE ROLE pl_s41_docente_executor NOLOGIN NOINHERIT NOSUPERUSER NOCREATEDB NOCREATEROLE NOREPLICATION NOBYPASSRLS;
EXCEPTION WHEN duplicate_object THEN NULL; END $$;
DO $$
DECLARE v_rol RECORD; v_cliente TEXT;
BEGIN
    FOR v_rol IN SELECT rolname,rolcanlogin,rolsuper,rolcreatedb,rolcreaterole,rolinherit,rolbypassrls
      FROM pg_catalog.pg_roles WHERE rolname IN ('pl_s41_docente_owner','pl_s41_docente_executor')
    LOOP
      IF v_rol.rolcanlogin OR v_rol.rolsuper OR v_rol.rolcreatedb OR v_rol.rolcreaterole
         OR v_rol.rolinherit OR v_rol.rolbypassrls THEN
        RAISE EXCEPTION 'El rol privado S4.1 tiene atributos no seguros';
      END IF;
    END LOOP;
    FOREACH v_cliente IN ARRAY ARRAY['anon','authenticated','service_role'] LOOP
      IF pg_catalog.pg_has_role(v_cliente,'pl_s41_docente_executor','MEMBER')
         OR pg_catalog.pg_has_role(v_cliente,'pl_s41_docente_owner','MEMBER') THEN
        RAISE EXCEPTION 'Un rol cliente pertenece a un rol privado S4.1';
      END IF;
    END LOOP;
END $$;
