CREATE TABLE IF NOT EXISTS public.dispositivo_push (
    id_dispositivo BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES public.usuario (id_usuario) ON DELETE CASCADE,
    token TEXT NOT NULL UNIQUE,
    plataforma VARCHAR(20) NOT NULL CHECK (plataforma IN ('android', 'ios')),
    activo BOOLEAN NOT NULL DEFAULT TRUE,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS idx_dispositivo_push_usuario_activo
    ON public.dispositivo_push (id_usuario) WHERE activo;

CREATE OR REPLACE FUNCTION public.fn_registrar_dispositivo_push(
    p_id_usuario BIGINT, p_token TEXT, p_plataforma VARCHAR
) RETURNS VOID
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
BEGIN
    INSERT INTO public.dispositivo_push (id_usuario, token, plataforma, activo, fecha_actualizacion)
    VALUES (p_id_usuario, p_token, p_plataforma, TRUE, NOW())
    ON CONFLICT (token) DO UPDATE SET
        id_usuario = EXCLUDED.id_usuario,
        plataforma = EXCLUDED.plataforma,
        activo = TRUE,
        fecha_actualizacion = NOW();
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_eliminar_dispositivo_push(
    p_id_usuario BIGINT, p_token TEXT
) RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_actualizados INTEGER;
BEGIN
    UPDATE public.dispositivo_push SET activo = FALSE, fecha_actualizacion = NOW()
    WHERE id_usuario = p_id_usuario AND activo AND token = p_token;
    GET DIAGNOSTICS v_actualizados = ROW_COUNT;
    RETURN v_actualizados;
END;
$$;

REVOKE ALL ON FUNCTION public.fn_registrar_dispositivo_push(BIGINT, TEXT, VARCHAR) FROM PUBLIC;
REVOKE ALL ON FUNCTION public.fn_eliminar_dispositivo_push(BIGINT, TEXT) FROM PUBLIC;

CREATE OR REPLACE FUNCTION public.fn_eliminar_dispositivos_usuario_push(
    p_id_usuario BIGINT
) RETURNS INTEGER
LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE v_actualizados INTEGER;
BEGIN
    UPDATE public.dispositivo_push SET activo = FALSE, fecha_actualizacion = NOW()
    WHERE id_usuario = p_id_usuario AND activo;
    GET DIAGNOSTICS v_actualizados = ROW_COUNT;
    RETURN v_actualizados;
END;
$$;
REVOKE ALL ON FUNCTION public.fn_eliminar_dispositivos_usuario_push(BIGINT) FROM PUBLIC;
