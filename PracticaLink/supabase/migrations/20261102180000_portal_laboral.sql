CREATE OR REPLACE FUNCTION public.fn_laboral_listar_ofertas(
    p_id_usuario BIGINT, p_solo_publicadas BOOLEAN
)
RETURNS JSONB
LANGUAGE plpgsql STABLE
SET search_path = public
AS $$
DECLARE
    v_es_empresa BOOLEAN;
    v_es_gestor BOOLEAN;
    v_rut_empresa VARCHAR(12);
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id_rol = ur.id_rol
        WHERE ur.id_usuario = p_id_usuario AND r.nombre = 'EMPRESA' AND r.activo
    ), EXISTS (
        SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id_rol = ur.id_rol
        WHERE ur.id_usuario = p_id_usuario AND r.nombre IN ('GESTOR', 'ADMINISTRADOR') AND r.activo
    ) INTO v_es_empresa, v_es_gestor;
    SELECT rut_empresa INTO v_rut_empresa FROM cuenta_empresa WHERE id_usuario = p_id_usuario;

    IF NOT p_solo_publicadas AND NOT v_es_gestor
        AND (NOT v_es_empresa OR v_rut_empresa IS NULL) THEN
        RETURN jsonb_build_object('error', 'USUARIO_NO_AUTORIZADO');
    END IF;
    RETURN (
        SELECT COALESCE(jsonb_agg(jsonb_build_object(
            'id_oferta', o.id_oferta, 'rut_empresa', o.rut_empresa,
            'empresa', COALESCE(emp.razon_social, cp.nombre, o.rut_empresa),
            'cargo', o.cargo, 'descripcion', o.descripcion,
            'ubicacion', o.ubicacion, 'modalidad', o.modalidad,
            'requisitos', o.requisitos, 'jornada', o.jornada,
            'fecha_publicacion', o.fecha_publicacion, 'fecha_cierre', o.fecha_cierre,
            'estado', o.estado, 'total_postulaciones', COALESCE(post.total, 0)
        ) ORDER BY COALESCE(o.fecha_publicacion, o.fecha_creacion) DESC, o.id_oferta DESC), '[]'::JSONB)
        FROM oferta_laboral o
        LEFT JOIN empresa emp ON UPPER(emp.rut) = UPPER(o.rut_empresa)
        LEFT JOIN centro_practica cp ON UPPER(cp.rut_empresa) = UPPER(o.rut_empresa)
        LEFT JOIN LATERAL (
            SELECT COUNT(*) AS total FROM postulacion_laboral pl
            WHERE pl.id_oferta = o.id_oferta
        ) post ON TRUE
        WHERE (
            (p_solo_publicadas AND o.estado = 'PUBLICADA'
                AND (o.fecha_cierre IS NULL OR o.fecha_cierre >= CURRENT_DATE))
            OR (NOT p_solo_publicadas AND (
                v_es_gestor OR (v_es_empresa AND UPPER(o.rut_empresa) = UPPER(v_rut_empresa))
            ))
        )
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_laboral_detalle_oferta(
    p_id_usuario BIGINT, p_id_oferta BIGINT, p_solo_publicada BOOLEAN
)
RETURNS JSONB
LANGUAGE plpgsql STABLE
SET search_path = public
AS $$
DECLARE
    v_resultado JSONB;
    v_ofertas JSONB;
BEGIN
    v_ofertas := public.fn_laboral_listar_ofertas(p_id_usuario, p_solo_publicada);
    IF jsonb_typeof(v_ofertas) = 'object' AND v_ofertas ? 'error' THEN
        RETURN v_ofertas;
    END IF;
    SELECT item INTO v_resultado
    FROM (
        SELECT jsonb_array_elements(v_ofertas) AS item
    ) q
    WHERE (item ->> 'id_oferta')::BIGINT = p_id_oferta
          AND (NOT p_solo_publicada OR item ->> 'estado' = 'PUBLICADA');
    IF v_resultado IS NULL THEN
        RETURN jsonb_build_object('error', 'OFERTA_NO_ENCONTRADA');
    END IF;
    RETURN v_resultado;
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_laboral_guardar_oferta(
    p_id_usuario BIGINT, p_id_oferta BIGINT, p_datos JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_es_empresa BOOLEAN;
    v_es_gestor BOOLEAN;
    v_rut_empresa VARCHAR(12);
    v_oferta oferta_laboral%ROWTYPE;
    v_estado VARCHAR(20);
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id_rol = ur.id_rol
        WHERE ur.id_usuario = p_id_usuario AND r.nombre = 'EMPRESA' AND r.activo
    ), EXISTS (
        SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id_rol = ur.id_rol
        WHERE ur.id_usuario = p_id_usuario AND r.nombre IN ('GESTOR', 'ADMINISTRADOR') AND r.activo
    ) INTO v_es_empresa, v_es_gestor;
    IF NOT EXISTS (SELECT 1 FROM usuario WHERE id_usuario = p_id_usuario AND activo)
        OR (NOT v_es_empresa AND NOT v_es_gestor) THEN
        RETURN jsonb_build_object('error', 'USUARIO_NO_AUTORIZADO');
    END IF;
    IF v_es_empresa THEN
        SELECT ce.rut_empresa INTO v_rut_empresa
        FROM cuenta_empresa ce WHERE ce.id_usuario = p_id_usuario;
        IF v_rut_empresa IS NULL THEN
            RETURN jsonb_build_object('error', 'CUENTA_EMPRESA_NO_CONFIGURADA');
        END IF;
    ELSE
        v_rut_empresa := NULLIF(BTRIM(p_datos ->> 'rut_empresa'), '');
        IF v_rut_empresa IS NULL THEN
            RETURN jsonb_build_object('error', 'RUT_EMPRESA_REQUERIDO');
        END IF;
    END IF;
    v_estado := UPPER(COALESCE(NULLIF(p_datos ->> 'estado', ''), 'PUBLICADA'));
    IF v_estado NOT IN ('BORRADOR', 'PUBLICADA', 'CERRADA') THEN
        RETURN jsonb_build_object('error', 'DATOS_OFERTA_INVALIDOS');
    END IF;

    IF p_id_oferta IS NULL THEN
        INSERT INTO oferta_laboral (
            id_usuario_creador, rut_empresa, cargo, descripcion, ubicacion,
            modalidad, requisitos, jornada, fecha_publicacion, fecha_cierre, estado
        ) VALUES (
            p_id_usuario, v_rut_empresa, BTRIM(p_datos ->> 'cargo'),
            BTRIM(p_datos ->> 'descripcion'), BTRIM(p_datos ->> 'ubicacion'),
            UPPER(p_datos ->> 'modalidad'), BTRIM(p_datos ->> 'requisitos'),
            UPPER(p_datos ->> 'jornada'),
            CASE WHEN v_estado = 'PUBLICADA' THEN NOW() ELSE NULL END,
            NULLIF(p_datos ->> 'fecha_cierre', '')::DATE, v_estado
        ) RETURNING * INTO v_oferta;
    ELSE
        UPDATE oferta_laboral SET
            cargo = BTRIM(p_datos ->> 'cargo'),
            descripcion = BTRIM(p_datos ->> 'descripcion'),
            ubicacion = BTRIM(p_datos ->> 'ubicacion'),
            modalidad = UPPER(p_datos ->> 'modalidad'),
            requisitos = BTRIM(p_datos ->> 'requisitos'),
            jornada = UPPER(p_datos ->> 'jornada'),
            rut_empresa = CASE WHEN v_es_gestor THEN v_rut_empresa ELSE rut_empresa END,
            fecha_cierre = NULLIF(p_datos ->> 'fecha_cierre', '')::DATE,
            fecha_publicacion = CASE
                WHEN v_estado = 'PUBLICADA' THEN COALESCE(fecha_publicacion, NOW())
                ELSE fecha_publicacion
            END,
            estado = v_estado,
            fecha_actualizacion = NOW()
        WHERE id_oferta = p_id_oferta
          AND (v_es_gestor OR UPPER(rut_empresa) = UPPER(v_rut_empresa))
        RETURNING * INTO v_oferta;
        IF NOT FOUND THEN
            RETURN jsonb_build_object('error', 'OFERTA_NO_ENCONTRADA');
        END IF;
    END IF;
    RETURN jsonb_build_object(
        'id_oferta', v_oferta.id_oferta, 'rut_empresa', v_oferta.rut_empresa,
        'cargo', v_oferta.cargo, 'estado', v_oferta.estado,
        'mensaje', 'Oferta guardada correctamente'
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_laboral_postular(
    p_id_usuario BIGINT, p_id_oferta BIGINT, p_carta_presentacion TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_id_estudiante BIGINT;
    v_id_postulacion BIGINT;
    v_id_historial BIGINT;
    v_estado_oferta VARCHAR(20);
BEGIN
    SELECT e.id_estudiante INTO v_id_estudiante
    FROM usuario u
    JOIN usuario_rol ur ON ur.id_usuario = u.id_usuario
    JOIN rol r ON r.id_rol = ur.id_rol AND r.nombre = 'ESTUDIANTE' AND r.activo
    JOIN estudiante e ON e.id_usuario = u.id_usuario
    WHERE u.id_usuario = p_id_usuario AND u.activo;
    IF v_id_estudiante IS NULL THEN
        RETURN jsonb_build_object('error', 'PERFIL_ESTUDIANTE_NO_ENCONTRADO');
    END IF;
    SELECT estado INTO v_estado_oferta
    FROM oferta_laboral
    WHERE id_oferta = p_id_oferta
      AND (fecha_cierre IS NULL OR fecha_cierre >= CURRENT_DATE)
    FOR UPDATE;
    IF NOT FOUND OR v_estado_oferta <> 'PUBLICADA' THEN
        RETURN jsonb_build_object('error', 'OFERTA_NO_DISPONIBLE');
    END IF;

    INSERT INTO postulacion_laboral (
        id_oferta, id_estudiante, carta_presentacion
    ) VALUES (
        p_id_oferta, v_id_estudiante, NULLIF(BTRIM(p_carta_presentacion), '')
    ) ON CONFLICT (id_oferta, id_estudiante) DO NOTHING
    RETURNING id_postulacion INTO v_id_postulacion;
    IF v_id_postulacion IS NULL THEN
        RETURN jsonb_build_object('error', 'POSTULACION_DUPLICADA');
    END IF;
    INSERT INTO historial_postulacion_laboral (
        id_postulacion, id_usuario, estado_nuevo
    ) VALUES (v_id_postulacion, p_id_usuario, 'RECIBIDA')
    RETURNING id_historial INTO v_id_historial;
    RETURN jsonb_build_object(
        'id_postulacion', v_id_postulacion, 'estado', 'RECIBIDA',
        'mensaje', 'Postulación enviada correctamente'
    );
END;
$$;

