CREATE OR REPLACE FUNCTION public.fn_laboral_actualizar_postulacion(
    p_id_usuario BIGINT, p_id_postulacion BIGINT,
    p_estado VARCHAR, p_observacion TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_es_empresa BOOLEAN;
    v_es_gestor BOOLEAN;
    v_rut_empresa VARCHAR(12);
    v_postulacion postulacion_laboral%ROWTYPE;
BEGIN
    SELECT EXISTS (
        SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id_rol = ur.id_rol
        WHERE ur.id_usuario = p_id_usuario AND r.nombre = 'EMPRESA' AND r.activo
    ), EXISTS (
        SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id_rol = ur.id_rol
        WHERE ur.id_usuario = p_id_usuario AND r.nombre IN ('GESTOR', 'ADMINISTRADOR') AND r.activo
    ) INTO v_es_empresa, v_es_gestor;
    SELECT rut_empresa INTO v_rut_empresa FROM cuenta_empresa WHERE id_usuario = p_id_usuario;
    IF NOT v_es_gestor AND NOT v_es_empresa THEN
        RETURN jsonb_build_object('error', 'USUARIO_NO_AUTORIZADO');
    END IF;
    SELECT pl.* INTO v_postulacion
    FROM postulacion_laboral pl
    JOIN oferta_laboral o ON o.id_oferta = pl.id_oferta
    WHERE pl.id_postulacion = p_id_postulacion
      AND (v_es_gestor OR UPPER(o.rut_empresa) = UPPER(v_rut_empresa))
    FOR UPDATE OF pl;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('error', 'POSTULACION_NO_ENCONTRADA');
    END IF;
    IF p_estado IS NULL OR p_estado NOT IN (
        'RECIBIDA', 'EN_REVISION', 'SELECCIONADA', 'RECHAZADA'
    ) THEN
        RETURN jsonb_build_object('error', 'ESTADO_POSTULACION_INVALIDO');
    END IF;
    IF v_postulacion.estado <> p_estado THEN
        UPDATE postulacion_laboral SET estado = p_estado, fecha_actualizacion = NOW()
        WHERE id_postulacion = p_id_postulacion;
        INSERT INTO historial_postulacion_laboral (
            id_postulacion, id_usuario, estado_anterior, estado_nuevo, observacion
        ) VALUES (
            p_id_postulacion, p_id_usuario, v_postulacion.estado, p_estado,
            NULLIF(BTRIM(p_observacion), '')
        );
    END IF;
    RETURN jsonb_build_object(
        'id_postulacion', p_id_postulacion, 'estado', p_estado,
        'mensaje', 'Estado de postulación actualizado'
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_laboral_historial_postulacion(
    p_id_usuario BIGINT, p_id_postulacion BIGINT
)
RETURNS JSONB
LANGUAGE plpgsql STABLE
SET search_path = public
AS $$
DECLARE
    v_es_autorizado BOOLEAN;
    v_rut_empresa VARCHAR(12);
BEGIN
    SELECT rut_empresa INTO v_rut_empresa
    FROM cuenta_empresa WHERE id_usuario = p_id_usuario;
    SELECT EXISTS (
        SELECT 1
        FROM postulacion_laboral pl
        JOIN oferta_laboral o ON o.id_oferta = pl.id_oferta
        LEFT JOIN estudiante e ON e.id_estudiante = pl.id_estudiante
        WHERE pl.id_postulacion = p_id_postulacion
          AND (
              e.id_usuario = p_id_usuario
              OR UPPER(o.rut_empresa) = UPPER(v_rut_empresa)
              OR EXISTS (
                  SELECT 1 FROM usuario_rol ur JOIN rol r ON r.id_rol = ur.id_rol
                  WHERE ur.id_usuario = p_id_usuario
                    AND r.nombre IN ('GESTOR', 'ADMINISTRADOR') AND r.activo
              )
          )
    ) INTO v_es_autorizado;
    IF NOT v_es_autorizado THEN
        RETURN jsonb_build_object('error', 'POSTULACION_NO_ENCONTRADA');
    END IF;
    RETURN (
        SELECT COALESCE(jsonb_agg(jsonb_build_object(
            'estado_anterior', h.estado_anterior, 'estado_nuevo', h.estado_nuevo,
            'observacion', h.observacion, 'fecha_cambio', h.fecha_cambio,
            'usuario', CONCAT(u.nombre, ' ', u.apellido)
        ) ORDER BY h.fecha_cambio, h.id_historial), '[]'::JSONB)
        FROM historial_postulacion_laboral h
        JOIN usuario u ON u.id_usuario = h.id_usuario
        WHERE h.id_postulacion = p_id_postulacion
    );
END;
