CREATE OR REPLACE FUNCTION public.fn_laboral_resolver_solicitud_empresa(
    p_id_admin BIGINT,
    p_id_solicitud BIGINT,
    p_estado VARCHAR,
    p_observacion TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_solicitud solicitud_cuenta_empresa%ROWTYPE;
    v_id_usuario BIGINT;
    v_id_rol_empresa BIGINT;
BEGIN
    IF NOT EXISTS (
        SELECT 1
        FROM usuario u
        JOIN usuario_rol ur ON ur.id_usuario = u.id_usuario
        JOIN rol r ON r.id_rol = ur.id_rol
        WHERE u.id_usuario = p_id_admin AND u.activo
          AND r.nombre = 'ADMINISTRADOR' AND r.activo
    ) THEN
        RETURN jsonb_build_object('error', 'ADMIN_NO_VALIDO');
    END IF;
    IF p_estado IS NULL OR p_estado NOT IN ('APROBADA', 'RECHAZADA') THEN
        RETURN jsonb_build_object('error', 'ESTADO_SOLICITUD_INVALIDO');
    END IF;

    SELECT * INTO v_solicitud
    FROM solicitud_cuenta_empresa
    WHERE id_solicitud = p_id_solicitud
    FOR UPDATE;
    IF NOT FOUND THEN
        RETURN jsonb_build_object('error', 'SOLICITUD_EMPRESA_NO_ENCONTRADA');
    END IF;
    IF v_solicitud.estado <> 'PENDIENTE' THEN
        RETURN jsonb_build_object('error', 'SOLICITUD_EMPRESA_YA_RESUELTA');
    END IF;
    IF p_estado = 'RECHAZADA' THEN
        UPDATE solicitud_cuenta_empresa SET
            estado = p_estado,
            observacion_revision = NULLIF(BTRIM(p_observacion), ''),
            id_admin_revision = p_id_admin,
            fecha_revision = NOW(),
            password_hash = NULL
        WHERE id_solicitud = p_id_solicitud;
        RETURN jsonb_build_object(
            'id_solicitud', p_id_solicitud,
            'estado', p_estado,
            'mensaje', 'Solicitud rechazada'
        );
    END IF;

    IF EXISTS (
        SELECT 1 FROM usuario
        WHERE LOWER(correo) = LOWER(v_solicitud.correo)
    ) THEN
        RETURN jsonb_build_object('error', 'CORREO_EMPRESA_DUPLICADO');
    END IF;
    IF EXISTS (
        SELECT 1 FROM cuenta_empresa
        WHERE UPPER(rut_empresa) = UPPER(v_solicitud.rut_empresa)
    ) THEN
        RETURN jsonb_build_object('error', 'RUT_EMPRESA_DUPLICADO');
    END IF;
    SELECT id_rol INTO v_id_rol_empresa
    FROM rol WHERE nombre = 'EMPRESA' AND activo;
    IF v_id_rol_empresa IS NULL OR v_solicitud.password_hash IS NULL THEN
        RETURN jsonb_build_object('error', 'SOLICITUD_EMPRESA_NO_VALIDA');
    END IF;

    BEGIN
        INSERT INTO usuario (nombre, apellido, correo, password_hash)
        VALUES (
            v_solicitud.nombre_contacto,
            v_solicitud.apellido_contacto,
            LOWER(v_solicitud.correo),
            v_solicitud.password_hash
        )
        RETURNING id_usuario INTO v_id_usuario;
        INSERT INTO usuario_rol (id_usuario, id_rol)
        VALUES (v_id_usuario, v_id_rol_empresa);
        INSERT INTO cuenta_empresa (id_usuario, rut_empresa)
        VALUES (v_id_usuario, v_solicitud.rut_empresa);
        INSERT INTO empresa (rut, dv, razon_social, fuente, consultado_en)
        VALUES (
            v_solicitud.rut_empresa,
            RIGHT(v_solicitud.rut_empresa, 1),
            v_solicitud.razon_social,
            'Solicitud empresarial',
            NOW()
        )
        ON CONFLICT (rut) DO NOTHING;
        UPDATE solicitud_cuenta_empresa SET
            estado = p_estado,
            observacion_revision = NULLIF(BTRIM(p_observacion), ''),
            id_admin_revision = p_id_admin,
            fecha_revision = NOW(),
            password_hash = NULL
        WHERE id_solicitud = p_id_solicitud;
    EXCEPTION WHEN unique_violation THEN
        RETURN jsonb_build_object('error', 'SOLICITUD_EMPRESA_DUPLICADA');
    END;

    RETURN jsonb_build_object(
        'id_solicitud', p_id_solicitud,
        'id_usuario', v_id_usuario,
        'estado', p_estado,
        'mensaje', 'Solicitud aprobada y cuenta empresa creada'
    );
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_laboral_practicas_empresa(p_id_usuario BIGINT)
