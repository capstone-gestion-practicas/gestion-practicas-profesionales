CREATE OR REPLACE FUNCTION public.fn_listar_usuarios()
RETURNS JSONB
LANGUAGE sql STABLE
SET search_path = public
AS $$
    SELECT COALESCE(jsonb_agg(jsonb_build_object(
        'id_usuario', q.id_usuario, 'nombre', q.nombre,
        'apellido', q.apellido, 'correo', q.correo,
        'activo', q.activo, 'roles', q.roles,
        'rut_empresa', q.rut_empresa
    ) ORDER BY q.apellido, q.nombre), '[]'::JSONB)
    FROM (
        SELECT u.id_usuario, u.nombre, u.apellido, u.correo, u.activo,
            ce.rut_empresa,
            COALESCE(array_agg(r.nombre ORDER BY r.nombre)
                FILTER (WHERE r.id_rol IS NOT NULL), ARRAY[]::VARCHAR[]) AS roles
        FROM usuario u
        LEFT JOIN usuario_rol ur ON ur.id_usuario = u.id_usuario
        LEFT JOIN rol r ON r.id_rol = ur.id_rol
        LEFT JOIN cuenta_empresa ce ON ce.id_usuario = u.id_usuario
        GROUP BY u.id_usuario, ce.rut_empresa
    ) q;
$$;

CREATE OR REPLACE FUNCTION public.fn_crear_usuario_admin(
    p_id_admin BIGINT, p_datos JSONB, p_password_hash VARCHAR
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_id_usuario BIGINT;
    v_roles_solicitados INTEGER;
    v_roles_validos INTEGER;
    v_es_empresa BOOLEAN;
    v_rut_empresa VARCHAR(12);
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM usuario_rol ur
        JOIN usuario u ON u.id_usuario = ur.id_usuario
        JOIN rol r ON r.id_rol = ur.id_rol
        WHERE u.id_usuario = p_id_admin AND u.activo
          AND r.nombre = 'ADMINISTRADOR' AND r.activo
    ) THEN RETURN jsonb_build_object('error', 'ADMIN_NO_VALIDO'); END IF;
    IF EXISTS (
        SELECT 1 FROM usuario
        WHERE LOWER(correo) = LOWER(BTRIM(p_datos ->> 'correo'))
    ) THEN RETURN jsonb_build_object('error', 'CORREO_EXISTENTE'); END IF;

    SELECT COUNT(DISTINCT UPPER(role_name)) INTO v_roles_solicitados
    FROM jsonb_array_elements_text(COALESCE(p_datos -> 'roles', '[]'::JSONB)) AS roles(role_name);
    SELECT COUNT(DISTINCT r.nombre) INTO v_roles_validos
    FROM rol r WHERE r.activo AND r.nombre IN (
        SELECT UPPER(role_name)
        FROM jsonb_array_elements_text(COALESCE(p_datos -> 'roles', '[]'::JSONB)) AS roles(role_name)
    );
    IF v_roles_solicitados = 0 OR v_roles_solicitados <> v_roles_validos THEN
        RETURN jsonb_build_object('error', 'ROLES_INVALIDOS');
    END IF;

    SELECT EXISTS (
        SELECT 1 FROM jsonb_array_elements_text(p_datos -> 'roles') AS roles(role_name)
        WHERE UPPER(role_name) = 'EMPRESA'
    ) INTO v_es_empresa;
    IF v_es_empresa AND v_roles_solicitados <> 1 THEN
        RETURN jsonb_build_object('error', 'ROLES_INVALIDOS');
    END IF;
    IF v_es_empresa THEN
        v_rut_empresa := NULLIF(BTRIM(p_datos ->> 'rut_empresa'), '');
        IF v_rut_empresa IS NULL THEN
            RETURN jsonb_build_object('error', 'RUT_EMPRESA_REQUERIDO');
        END IF;
        IF EXISTS (
            SELECT 1 FROM cuenta_empresa WHERE rut_empresa = v_rut_empresa
        ) THEN RETURN jsonb_build_object('error', 'RUT_EMPRESA_EXISTENTE'); END IF;
    ELSIF NULLIF(BTRIM(p_datos ->> 'rut_empresa'), '') IS NOT NULL THEN
        RETURN jsonb_build_object('error', 'ROLES_INVALIDOS');
    END IF;

    INSERT INTO usuario (nombre, apellido, correo, password_hash)
    VALUES (BTRIM(p_datos ->> 'nombre'), BTRIM(p_datos ->> 'apellido'),
        LOWER(BTRIM(p_datos ->> 'correo')), p_password_hash)
    RETURNING id_usuario INTO v_id_usuario;
    INSERT INTO usuario_rol (id_usuario, id_rol)
    SELECT v_id_usuario, r.id_rol FROM rol r
    WHERE r.activo AND r.nombre IN (
        SELECT UPPER(role_name)
        FROM jsonb_array_elements_text(p_datos -> 'roles') AS roles(role_name)
    );
    IF v_es_empresa THEN
        BEGIN
            INSERT INTO cuenta_empresa (id_usuario, rut_empresa)
            VALUES (v_id_usuario, v_rut_empresa);
        EXCEPTION WHEN unique_violation THEN
            RETURN jsonb_build_object('error', 'RUT_EMPRESA_EXISTENTE');
        END;
    END IF;
    RETURN jsonb_build_object('id_usuario', v_id_usuario, 'mensaje', 'Usuario creado correctamente');
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_actualizar_usuario_admin(
    p_id_admin BIGINT, p_id_usuario BIGINT, p_datos JSONB
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_roles_solicitados INTEGER;
    v_roles_validos INTEGER;
    v_conserva_admin BOOLEAN;
    v_es_empresa BOOLEAN;
    v_rut_empresa VARCHAR(12);
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM usuario_rol ur
        JOIN usuario u ON u.id_usuario = ur.id_usuario
        JOIN rol r ON r.id_rol = ur.id_rol
        WHERE u.id_usuario = p_id_admin AND u.activo
          AND r.nombre = 'ADMINISTRADOR' AND r.activo
    ) THEN RETURN jsonb_build_object('error', 'ADMIN_NO_VALIDO'); END IF;
    PERFORM 1 FROM usuario WHERE id_usuario = p_id_usuario FOR UPDATE;
    IF NOT FOUND THEN RETURN jsonb_build_object('error', 'USUARIO_NO_ENCONTRADO'); END IF;

    SELECT COUNT(DISTINCT UPPER(role_name)) INTO v_roles_solicitados
    FROM jsonb_array_elements_text(COALESCE(p_datos -> 'roles', '[]'::JSONB)) AS roles(role_name);
    SELECT COUNT(DISTINCT r.nombre) INTO v_roles_validos
    FROM rol r WHERE r.activo AND r.nombre IN (
        SELECT UPPER(role_name)
        FROM jsonb_array_elements_text(COALESCE(p_datos -> 'roles', '[]'::JSONB)) AS roles(role_name)
    );
    IF v_roles_solicitados = 0 OR v_roles_solicitados <> v_roles_validos THEN
        RETURN jsonb_build_object('error', 'ROLES_INVALIDOS');
    END IF;
    SELECT EXISTS (
        SELECT 1 FROM jsonb_array_elements_text(p_datos -> 'roles') AS roles(role_name)
        WHERE UPPER(role_name) = 'ADMINISTRADOR'
    ) INTO v_conserva_admin;
    IF p_id_admin = p_id_usuario AND (
        (p_datos ->> 'activo')::BOOLEAN = FALSE OR NOT v_conserva_admin
    ) THEN RETURN jsonb_build_object('error', 'AUTOGESTION_NO_PERMITIDA'); END IF;

    SELECT EXISTS (
        SELECT 1 FROM jsonb_array_elements_text(p_datos -> 'roles') AS roles(role_name)
        WHERE UPPER(role_name) = 'EMPRESA'
    ) INTO v_es_empresa;
    IF v_es_empresa AND v_roles_solicitados <> 1 THEN
        RETURN jsonb_build_object('error', 'ROLES_INVALIDOS');
    END IF;
    IF v_es_empresa THEN
        v_rut_empresa := NULLIF(BTRIM(p_datos ->> 'rut_empresa'), '');
        IF v_rut_empresa IS NULL THEN
            RETURN jsonb_build_object('error', 'RUT_EMPRESA_REQUERIDO');
        END IF;
        IF EXISTS (
            SELECT 1 FROM cuenta_empresa
            WHERE rut_empresa = v_rut_empresa AND id_usuario <> p_id_usuario
        ) THEN RETURN jsonb_build_object('error', 'RUT_EMPRESA_EXISTENTE'); END IF;
    ELSIF NULLIF(BTRIM(p_datos ->> 'rut_empresa'), '') IS NOT NULL THEN
        RETURN jsonb_build_object('error', 'ROLES_INVALIDOS');
    END IF;

    UPDATE usuario SET nombre = BTRIM(p_datos ->> 'nombre'),
        apellido = BTRIM(p_datos ->> 'apellido'),
        activo = (p_datos ->> 'activo')::BOOLEAN,
        fecha_actualizacion = NOW()
    WHERE id_usuario = p_id_usuario;
    DELETE FROM usuario_rol WHERE id_usuario = p_id_usuario;
    INSERT INTO usuario_rol (id_usuario, id_rol)
    SELECT p_id_usuario, r.id_rol FROM rol r
    WHERE r.activo AND r.nombre IN (
        SELECT UPPER(role_name)
        FROM jsonb_array_elements_text(p_datos -> 'roles') AS roles(role_name)
    );
    IF v_es_empresa THEN
        BEGIN
            INSERT INTO cuenta_empresa (id_usuario, rut_empresa)
            VALUES (p_id_usuario, v_rut_empresa)
            ON CONFLICT (id_usuario) DO UPDATE SET
                rut_empresa = EXCLUDED.rut_empresa,
                fecha_actualizacion = NOW();
        EXCEPTION WHEN unique_violation THEN
            RETURN jsonb_build_object('error', 'RUT_EMPRESA_EXISTENTE');
        END;
    ELSE
        DELETE FROM cuenta_empresa WHERE id_usuario = p_id_usuario;
    END IF;
    RETURN jsonb_build_object('id_usuario', p_id_usuario, 'mensaje', 'Usuario actualizado correctamente');
END;
$$;

CREATE OR REPLACE FUNCTION public.fn_laboral_solicitar_cuenta_empresa(
    p_datos JSONB, p_password_hash TEXT
)
RETURNS JSONB
LANGUAGE plpgsql
SET search_path = public
AS $$
DECLARE
    v_id_solicitud BIGINT;
BEGIN
    IF EXISTS (
        SELECT 1 FROM usuario
        WHERE LOWER(correo) = LOWER(BTRIM(p_datos ->> 'correo'))
    ) OR EXISTS (
        SELECT 1 FROM cuenta_empresa
        WHERE UPPER(rut_empresa) = UPPER(BTRIM(p_datos ->> 'rut_empresa'))
    ) OR EXISTS (
        SELECT 1 FROM solicitud_cuenta_empresa
        WHERE estado = 'PENDIENTE'
          AND (
              LOWER(correo) = LOWER(BTRIM(p_datos ->> 'correo'))
              OR UPPER(rut_empresa) = UPPER(BTRIM(p_datos ->> 'rut_empresa'))
          )
    ) THEN
        RETURN jsonb_build_object('error', 'SOLICITUD_EMPRESA_DUPLICADA');
    END IF;

    INSERT INTO solicitud_cuenta_empresa (
        razon_social, rut_empresa, nombre_contacto, apellido_contacto,
        correo, telefono, cargo_contacto, password_hash
    ) VALUES (
        BTRIM(p_datos ->> 'razon_social'),
        BTRIM(p_datos ->> 'rut_empresa'),
        BTRIM(p_datos ->> 'nombre_contacto'),
        BTRIM(p_datos ->> 'apellido_contacto'),
        LOWER(BTRIM(p_datos ->> 'correo')),
        BTRIM(p_datos ->> 'telefono'),
        BTRIM(p_datos ->> 'cargo_contacto'),
        p_password_hash
    )
    RETURNING id_solicitud INTO v_id_solicitud;

    RETURN jsonb_build_object(
        'id_solicitud', v_id_solicitud,
        'estado', 'PENDIENTE',
        'mensaje', 'Solicitud enviada para revisión'
    );
EXCEPTION WHEN unique_violation THEN
    RETURN jsonb_build_object('error', 'SOLICITUD_EMPRESA_DUPLICADA');
END;
$$;

