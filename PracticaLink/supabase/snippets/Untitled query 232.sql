CREATE TABLE IF NOT EXISTS notificacion (
    id_notificacion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT NOT NULL REFERENCES usuario (id_usuario) ON DELETE CASCADE,
    id_practica BIGINT NOT NULL REFERENCES practica (id_practica) ON DELETE CASCADE,
    tipo VARCHAR(40) NOT NULL,
    titulo VARCHAR(150) NOT NULL,
    mensaje VARCHAR(500) NOT NULL,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    fecha_leida TIMESTAMPTZ
);

CREATE INDEX IF NOT EXISTS idx_notificacion_usuario_fecha
    ON notificacion (id_usuario, fecha_creacion DESC);

CREATE INDEX IF NOT EXISTS idx_notificacion_no_leida
    ON notificacion (id_usuario, id_notificacion DESC)
    WHERE fecha_leida IS NULL;
